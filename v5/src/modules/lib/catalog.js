/** 判断这套设置是否真的需要注入写作指令（纯闲聊时不注入，避免无谓变慢）。 */
function hasWritingIntent(w) {
  if (!w) return false;
  if (w.scene && w.scene !== 'auto') return true;
  if (w.intent && w.intent !== 'chat') return true;
  if (w.requirements && w.requirements.trim()) return true;
  if (w.audience && w.audience.trim()) return true;
  if (w.preference && w.preference.trim()) return true;
  if (w.style && w.style !== exports.STYLES[0]) return true;
  if (w.length && w.length !== exports.LENGTHS[1]) return true;
  if (w.intensity && w.intensity !== '标准') return true;
  return false;
}

/** 把写作设置拼成真正会进入 system 提示词的指令。 */
function buildWritingPrompt(w) {
  const scene = w && w.scene && w.scene !== 'auto' ? getScene(w.scene) : null;
  const lines = [];
  if (scene) {
    lines.push(`【写作场景】${scene.name}：${scene.instruction}`);
  } else {
    lines.push('【写作场景】自由创作：按用户的具体要求组织内容与结构，不要套用固定模板。');
  }
  const styleIdx = exports.STYLES.indexOf(w.style);
  if (styleIdx >= 0) lines.push(`【风格】${w.style}——${exports.STYLE_HINTS[styleIdx]}。`);
  if (w.length) lines.push(`【篇幅】${w.length}。这是硬性范围，写到范围内就收尾，不要拖长。`);
  if (w.audience && w.audience.trim()) lines.push(`【读者】内容是写给「${w.audience.trim()}」看的，用词与详略按这个对象调整。`);
  if (w.preference && w.preference.trim()) lines.push(`【输出偏好】优先满足：${w.preference.trim()}。`);
  if (w.intensity && INTENSITY[w.intensity]) lines.push(`【处理强度】${INTENSITY[w.intensity]}`);
  if (w.requirements && w.requirements.trim()) lines.push(`【用户额外要求·必须遵守】\n${w.requirements.trim()}`);
  lines.push('【硬性底线】只使用用户提供的信息与公认常识；不编造数据、引用、文献、经历、时间、价格与资质。信息不足时明确写"需要补充"，不要用看似合理的数字填空。');
  return lines.join('\n');
}

